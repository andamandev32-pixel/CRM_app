/* ---- ต้องเป็นหน่วยงานสายสาธารณสุข ---------------------------------------- */
const HEALTH = /โรงพยาบาล|สาธารณสุข|สถาบัน.*(แพทย|สุขภาพ|มะเร็ง|จิตเวช)|กรมการแพทย์|กรมอนามัย|กรมควบคุมโรค|ศูนย์อนามัย|วิทยาลัยพยาบาล|คณะแพทย|ศูนย์ศรีพัฒน์|ทันตกรรม|เภสัช|รพ\.|ราชวิทยาลัย|คณะทันตแพทย|สถาบัน(โรค|ประสาท|บำราศ|ราชานุกูล|บำบัดรักษา|สุขภาพ)|สถานีอนามัย|หลักประกันสุขภาพ|เขตสุขภาพ|ศูนย์การแพทย์|ศูนย์หัวใจ/;
/* หน่วยงานที่เกณฑ์เดิมตกหล่น (ตรวจ 18 ก.ย. 69): ราชวิทยาลัยจุฬาภรณ์ (ดีล PM ระบบ HIS 5 ล.),
   สถาบันโรคทรวงอก 6 โครงการ, สถาบันประสาทวิทยา 3, สถาบันบำราศนราดูร 2, คณะทันตแพทยศาสตร์ 5 */

/* ---- คำพ้องที่ต้องตัดทิ้ง (เจอจริงจากการทดสอบ) ---------------------------
   HIS      → BETAHISTINE / HISTIDINE (ชื่อยา)
   IPD      → "จ้างเหมาบริการพยาบาลวิชาชีพ (IPD)"
   บริหารจัดการยา → "บริหารจัดการยานพาหนะ" (ค่าน้ำมันรถโรงเรียน)
   Smart IPD → "LED Smart TV" ที่ติดในหอผู้ป่วย
   ------------------------------------------------------------------------- */
const FALSE_FRIENDS = new RegExp([
  'BETAHISTINE', 'HISTIDINE', 'HISTAMINE', 'ยานพาหนะ', 'Smart\\s*TV', 'LED\\s*Smart',
  // รอบตรวจ 18 ก.ย. 69 — ตู้บริการ ไปแมตช์ "จ้างเหมารถยนต์ตู้บริการต่างจังหวัด" (ค่าเช่ารถ)
  // ต้องดักที่คำว่า "รถ" ห้ามดักที่ "ตู้บริการ" เพราะเป็นคีย์เวิร์ด Kiosk ที่ถูกต้อง
  'รถตู้', 'รถยนต์ตู้', 'เหมารถ',
  // EMR ไปแมตช์ "ปฐมพยาบาลและช่วยปฎิบัติการแพทย์ขั้นพื้นฐาน EMR" (Emergency Medical Responder)
  'Medical\\s*Respon[sd]er',
  // HIS ไปแมตช์ "His pacing" / "His bundle" — การกระตุ้นหัวใจผ่านมัด His (เครื่องกระตุ้นหัวใจ)
  'His\\s*(?:pacing|bundle)',
].join('|'), 'i');

/* ---- คัดออกตามเกณฑ์ที่ไฟล์ .md ต้นทางประกาศไว้เอง ------------------------ */
const EXCLUDE = new RegExp([
  'ซื้อยา ', 'วัสดุการแพทย์', 'เวชภัณฑ์มิใช่ยา',          // ตัวยา/เวชภัณฑ์
  'จ้างเหมาบริการพยาบาล', 'พยาบาลวิชาชีพ', 'จ้างเหมาบุคลากร', 'จ้างเหมาพนักงาน',
  'ก่อสร้าง', 'ปรับปรุงพื้นที่', 'ปรับปรุงอาคาร', 'ต่อเติม', 'ตกแต่ง',
  'Cloud', 'คลาวด์', 'เครื่องแม่ข่าย', 'แม่ข่าย', 'ศูนย์ข้อมูล', 'Data\\s*Center',
  'เครือข่ายไร้สาย', 'WiFi', 'Wi-Fi', 'UPS', 'เครื่องสำรองไฟ',
  'เครื่องปรับอากาศ', 'กล้องวงจรปิด', 'ลิฟต์',
  'ปฐมพยาบาล', 'ฝึกอบรมหลักสูตร',                        // งานอบรม ไม่ใช่การจัดหาระบบ
  // "ซื้อวัสดุสำนักงาน เพื่อใช้ในโครงการพัฒนาระบบ…" = ของใช้สำนักงานของโครงการ ไม่ใช่ตัวระบบ
  // ผูกกับคำว่า "โครงการ" เท่านั้น ห้ามตัด 'วัสดุสำนักงาน' ลอย ๆ
  // เพราะจะไปโดนหมึกพิมพ์เครื่องจัดยา/กระดาษเทอร์มอลตู้ Kiosk ซึ่งเป็นยอดขาย consumable จริง
  'วัสดุสำนักงาน[^|]{0,40}โครงการ', 'โครงการ[^|]{0,40}วัสดุสำนักงาน',
].join('|'), 'i');

/* ---- ครุภัณฑ์/งานอาคารที่บังเอิญอยู่แผนกเวชระเบียน-คลังยา -----------------
   กฎนี้ตัดออก "เฉพาะเมื่อชื่อโครงการไม่ได้ระบุระบบเป้าหมาย" เพราะของที่ซื้อ
   *เพื่อระบบ* ถือเป็นดีลจริง — ชุดที่ตรวจยอดแล้วนับรายการพวกนี้เป็นของจริง เช่น
     "ครุภัณฑ์สำนักงาน (รถเข็น สำหรับ ระบบ IPD Paperless Medical Cart)"
     "ซื้อโต๊ะคอมพิวเตอร์แบบเคลื่อนที่ สำหรับระบบ IPD Paperless"
   ห้ามใช้ 'ครุภัณฑ์สำนักงาน' เป็นคำตัด — โรงพยาบาลลงบัญชีตู้ Kiosk ไว้ใต้หมวดนี้
   (รอบตรวจ 18 ก.ย. 69: ชน 17 แถวในชุดที่ล็อกไว้)
   -------------------------------------------------------------------------- */
const FACILITY = new RegExp([
  '(?:ปรับปรุง|ซ่อม|เชื่อมต่อ)[^|]{0,25}(?:ระบบไฟฟ้า|ไฟฟ้าสำรอง)',   // งานไฟฟ้าในห้องยา/ห้องบัตร
  'ประปา', 'สุขาภิบาล', 'ลูกบิด', 'ระบบ\\s*LAN',
  'รื้อย้าย', 'ขนย้าย', 'รางเลื่อน', 'เก็บแฟ้ม',                      // ย้าย/รื้อตู้แฟ้มเวชระเบียน
  'เคาน์เตอร์', 'เก้าอี้', 'โต๊ะทำงาน', 'โต๊ะคอมพิวเตอร์', 'โต๊ะหมู่',
  'เครื่องถ่ายเอกสาร', 'เครื่องทำลายเอกสาร',
  // งานอาคารรอบ ๆ ห้องคลัง — เจอตอนสำรวจกลุ่ม inv (18 ก.ย. 69)
  'ตู้แช่', 'อัคคีภัย', 'ท่อระบายน้ำ', 'ติดตามอุณหภูมิ', 'หลังคา',
  'แผ่นพับ', 'ชั้นวาง', 'กำจัดความชื้น', 'เสียงตามสาย',
].join('|'), 'i');

/* ชื่อระบบเป้าหมาย — มีคำพวกนี้แปลว่าซื้อ "เพื่อระบบ" ไม่ใช่ครุภัณฑ์ลอย ๆ */
const NAMES_SYSTEM = /IPD\s*Paperless|Paperless|ไร้กระดาษ|Kiosk|คีออส|HOSxP|\bHIS\b|สารสนเทศโรงพยาบาล|ระบบคิว|บัตรคิว|เรียกคิว|ATDPS|จัดยาอัตโนมัติ|จ่ายยาอัตโนมัติ/i;

/* ---- ต้องมีคำบ่งชี้ว่าเป็น "ระบบ/โปรแกรม" ไม่ใช่ของใช้ทั่วไป -------------- */
const IS_SYSTEM = /ระบบ|โปรแกรม|ซอฟต์แวร์|software|application|แอปพลิเคชัน|licen[cs]e|ลิขสิทธิ์|เครื่อง|ตู้|รถเข็น|หุ่นยนต์/i;

/* ---- ต้องอยู่ในขอบเขตของกลุ่มนั้นจริง ------------------------------------ */
const SCOPE = {
  med: /จัดยา|จ่ายยา|นับเม็ดยา|ตู้ยา|ตู้เก็บยา|รถเข็น.*ยา|ผสมยา|คลังยา|ซองยา|ซองบรรจุยา|บริหารยา|บันทึกการให้ยา|Administration Record|Smart\s*(OPD\/)?IPD|บริหารจัดการยา(?!นพาหนะ)/i,
  his: /สารสนเทศโรงพยาบาล|Hospital Information|\bHIS\b|HOSxP|e-?PHIS|Smehims|Paperless|ไร้กระดาษ|EMR|เวชระเบียน|ห้องบัตร|ทะเบียนผู้ป่วย|คิว|Kiosk|คีออส|ตู้บริการ|ตู้อเนกประสงค์|บริหารจัดการโรงพยาบาล|บริหารงานโรงพยาบาล|ระบบบริหารโรงพยาบาล|โรงพยาบาลอัจฉริยะ/i,
  // \b(?:H)?ERP\b สำคัญมาก — ถ้าใช้ ERP เฉย ๆ จะไปโดน CAT·ERP·ILLAR (เครื่องกำเนิดไฟฟ้า)
  // และ FISH·ERP·AYKEL (เครื่องช่วยหายใจ) ส่วน H? มีไว้เก็บ HERP Copilot ซึ่งเป็นตัวหลักของตลาดนี้
  // (?!ข้อมูล|ข้อสอบ) ต้องครอบทุกคำที่ลงท้ายด้วย "คลัง" — ไม่ใช่แค่ "ระบบคลัง"
  // เพราะ "โปรแกรมคลังข้อมูลด้านการแพทย์" (data warehouse) และ "คลังข้อสอบ" ไม่ใช่คลังสินค้า
  inv: /\b(?:H)?ERP\b|Enterprise\s*Resource|วางแผนทรัพยากร|บริหารทรัพยากรองค์กร|(?:บริหาร|ระบบ|จัดการ|โปรแกรม)คลัง(?!ข้อมูล|ข้อสอบ)|คลังเวชภัณฑ์|คลังสินค้า|คลังวัสดุ/i,
};

/**
 * ตัดสินว่ารายการจาก API ผ่านเกณฑ์ของกลุ่มนี้ไหม
 * @returns {{ok: boolean, reason?: string}}
 */
function accept(rec, groupId) {
  const name = rec.project_name || '';
  const org = (rec.dept_name || '') + ' ' + (rec.dept_sub_name || '');

  if (!HEALTH.test(org))        return { ok: false, reason: 'ไม่ใช่หน่วยงานสายสาธารณสุข' };
  if (FALSE_FRIENDS.test(name)) return { ok: false, reason: 'คำพ้อง (ชื่อยา/ยานพาหนะ/Smart TV)' };
  if (EXCLUDE.test(name))       return { ok: false, reason: 'นอกเกณฑ์ (ก่อสร้าง/โครงสร้างพื้นฐาน/บุคลากร/ตัวยา)' };
  if (FACILITY.test(name) && !NAMES_SYSTEM.test(name))
                                return { ok: false, reason: 'ครุภัณฑ์/งานอาคาร ไม่ได้ระบุระบบเป้าหมาย' };
  if (!IS_SYSTEM.test(name))    return { ok: false, reason: 'ไม่ใช่ระบบ/เครื่อง' };
  const scope = SCOPE[groupId];
  if (scope && !scope.test(name)) return { ok: false, reason: 'อยู่นอกขอบเขตของกลุ่ม' };
  return { ok: true };
}

